//! GEOS buffer vertex parity (captured from shapely 2.1.2 / GEOS 3.13.1).

use kct::geometry::shapely::{self as sh, Geom};

type Ring = Vec<(f64, f64)>;

fn sorted(g: &Geom) -> (Ring, Vec<Ring>) {
    let p = &g.polys()[0];
    let mut s = p.shell.clone();
    s.sort_by(|a, b| a.partial_cmp(b).unwrap());
    s.dedup();
    let holes = p
        .holes
        .iter()
        .map(|h| {
            let mut h = h.clone();
            h.sort_by(|a, b| a.partial_cmp(b).unwrap());
            h.dedup();
            h
        })
        .collect();
    (s, holes)
}

